# Number of rows
rows = 5

# Outer loop for each line
for i in range(1, rows + 1):
    
    # Calculate spaces
    spaces = " " * (rows - i)
    
    # Calculate stars
    stars = "*" * i
    
    # Print spaces and stars together
    print(spaces + stars)















